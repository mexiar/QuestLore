return function(env)
    local dialogue="<María observa el camino.> "..string.rep("Necesitamos proteger la aldea y a sus habitantes. ",30).."Última frase original completa."
    env.select(999600,dialogue,"Habla con María al final del camino.")
    local ns=env.login({language="fr",followPolestar=false,followRestedXP=false,attachToTracker=false})
    env.tick(0.2)
    local model=ns.history.live
    assert(model.kind=="preview" and model.language=="es" and model.requestedLanguage=="fr" and model.sourceLocale=="esMX","preview uses original client locale independently of story preference")
    assert(model.body:sub(1,27)==dialogue:sub(1,27) and model.body:sub(-3)=="…" and #model.body<#dialogue,"literal preview preserves actions, accents, order and ellipsis")
    assert(not model.body:find("Última frase",1,true),"preview is bounded instead of selecting later narrative sentences")
    assert(ns.Window.previewButton:IsShown() and ns.Window.fullTextButton:IsShown(),"active original preview is clickable")
    assert(#ns.db.history==0 and ns.history:Current().kind=="preview","preview is neither archived nor rebuilt into a missing notice")
    ns.Window.previewButton.scripts.OnClick()
    assert(ns.FullText.frame:IsShown() and ns.FullText.body:GetText():find(dialogue,1,true),"click opens unabridged original")
    assert(ns.FullText.body:GetText():find("Habla con María",1,true),"reader includes original objectives")
    ns.FullText:Close()
    ns.Window:SetMinimized(true);assert(not ns.Window.previewButton:IsShown())
    ns.Window:SetMinimized(false);assert(ns.Window.previewButton:IsShown())
    ns.Window.frame:SetSize(1200,100);ns.Window.frame.scripts.OnSizeChanged(ns.Window.frame)
    assert(ns.Window.wideLayout and ns.Window.previewButton:IsShown(),"wide detached preview keeps its click action")
    ns.Window.previewButton.scripts.OnClick();assert(ns.FullText.frame:IsShown());ns.FullText:Close()
    local text=string.rep("漢",450)
    local preview=ns.Text.Preview(text)
    assert(preview==string.rep("漢",420).."…","UTF-8 clipping never splits a multibyte character")
    assert(ns.Text.Preview("|cffffffff|Hquest:1|hMaría|h|r <mira>.")=="María <mira>…","display markup is stripped without altering names or actions")
    assert(ns.Text.Preview(" ")=="","empty original does not fabricate a preview")
    env.select(999601,"","Un objetivo original sin descripción.")
    ns.testEvents.scripts.OnEvent(ns.testEvents,"SUPER_TRACKING_CHANGED");env.tick(0.2)
    assert(ns.history.live.kind=="preview" and ns.history.live.body=="Un objetivo original sin descripción…","objective-only original is a valid preview")
    local source=ns.API.Read(999601);assert(source.objectives=="Un objetivo original sin descripción." and source.sourceLocale=="esMX")
    ns.Window:Render({id=13,key="quest:13",title="Curated",body="Authored summary.",kind="story"})
    assert(not ns.Window.previewButton:IsShown(),"authored summaries never inherit the preview click overlay")
    ns.Window:Render(ns.history.live)
    ns.Window.previewButton.scripts.OnClick();assert(ns.FullText.id==999601)
    env.select(999601)
    ns.testEvents.scripts.OnEvent(ns.testEvents,"QUEST_REMOVED",999601);env.tick(0.2)
    assert(ns.Window.currentID~=999601 and ns.FullText.id==nil and ns.FullText.body:GetText()=="" and ns.questSources[999601]==nil,"removed quest clears its preview and reader before selecting another context")
    assert(#ns.db.history==0 and ns.db.quests==nil,"source previews never persist as quest history")
    print("PASS: literal client-language fallback, clickable ellipsis, full reader, UTF-8, objective-only quests, wide/minimized state, source cleanup and archive exclusion")
end
